/** 反応データから作る問題：反応名 → 反応式（同じ種類の反応を誤答に） */
function rxQuestions() {
  return REACTIONS.filter(r => /[→⇌]/.test(r.eq)).map(r => {
    const others = REACTIONS.filter(x => x.id !== r.id && /[→⇌]/.test(x.eq) && x.eq !== r.eq);
    const same = others.filter(x => x.k === r.k), pool = (same.length >= 3 ? same : others).slice();
    const w = []; while (w.length < 3 && pool.length) w.push(pool.splice(Math.floor(Math.random() * pool.length), 1)[0].eq);
    return Q('rx_' + r.id, RX_KIND[r.k].n, `「${r.n}」の反応式は？`, r.eq, w, r.note);
  });
}
export const allQuestions = () => BANK.concat(rxQuestions());

/** 出題：まだ解いていない問題と、間違えた問題を優先する。hist[id] = [正解数, 誤答数] */
export function pickQuestion(hist = {}, exclude = []) {
  const qs = allQuestions().filter(q => !exclude.includes(q.id));
  const wt = q => { const h = hist[q.id]; if (!h) return 5; const [r, w] = h; return Math.max(.4, 1 + w * 3 - r * .8); };
  let tot = 0; for (const q of qs) tot += wt(q);
  let x = Math.random() * tot; for (const q of qs) { x -= wt(q); if (x < 0) return q; }
  return qs[0];
}
