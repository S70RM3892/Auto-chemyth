/** 盤面の物質ID一覧 → 成立している反応 */
export function activeReactions(ids) {
  const s = ids instanceof Set ? ids : new Set(ids);
  return REACTIONS.filter(r => r.need.every(x => s.has(x)));
}
/** id を足すと新たに成立する反応（ショップの目印・AI用） */
export function completes(ids, id) {
  const s = new Set(ids); if (s.has(id)) return [];
  return REACTIONS.filter(r => r.need.includes(id) && r.need.every(x => x === id || s.has(x)));
}
